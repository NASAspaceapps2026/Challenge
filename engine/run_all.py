"""Field Shift -- re-run the whole data pipeline after data/fields.geojson changes.

Use this after redrawing field polygons or adding new fields: every engine
script loops over fields.geojson, so one pass regenerates all per-field CSVs
and the web/data JSONs.

data/fields_attributes.csv is regenerated by slope_attributes.py (Python
port of gee_slope_export.js), so no GEE Code Editor step is needed anymore.

Run:
    python engine/run_all.py            # everything
    python engine/run_all.py --fast     # skip the slow GEE steps (reuse NDVI/spots)
"""

import subprocess
import sys
from pathlib import Path

ENGINE = Path(__file__).resolve().parent

# (script, needs_gee) in dependency order.
STEPS = [
    ("slope_attributes.py", True),   # slope/area per field (GEE, quick)
    ("gee_ndvi_export.py", True),    # NDVI time series per field (GEE, slow)
    ("smooth_ndvi.py", False),
    ("detect_phenology.py", False),
    ("fetch_climate.py", False),     # NASA POWER at fields centroid
    ("water_balance.py", False),
    ("bare_soil.py", False),
    ("predict_harvest.py", False),
    ("rain_odds.py", False),
    ("productivity.py", False),
    ("low_vigor_spots.py", True),    # recurrent low-vigor zones (GEE, slow)
    ("export_web_data.py", False),   # merges everything into web/data/
]


def main():
    fast = "--fast" in sys.argv
    for script, needs_gee in STEPS:
        if fast and needs_gee:
            print(f"-- skipping {script} (--fast)")
            continue
        print(f"== {script}")
        r = subprocess.run([sys.executable, str(ENGINE / script)])
        if r.returncode != 0:
            sys.exit(f"{script} failed (exit {r.returncode}); pipeline stopped.")
    print("pipeline done -- web/data/ is up to date.")


if __name__ == "__main__":
    main()
